const run = (text, opts = {}) => new TextRun({ text, font: FONT, size: SIZE, ...opts });

function p(text, opts = {}) {
  const children = Array.isArray(text) ? text : [run(text)];
  return new Paragraph({
    children,
    alignment: opts.align ?? AlignmentType.JUSTIFIED,
    indent: opts.noIndent ? undefined : { firstLine: INDENT },
    spacing: { line: LINE, before: 0, after: 0, ...(opts.spacing || {}) },
    keepNext: opts.keepNext,
  });
}

const center = (text, opts = {}) =>
  new Paragraph({
    children: [run(text, opts)],
    alignment: AlignmentType.CENTER,
    spacing: { line: LINE },
  });

const empty = () => new Paragraph({ children: [run("")], spacing: { line: LINE } });

function h1(text, { pageBreak = true } = {}) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    alignment: AlignmentType.CENTER,
    pageBreakBefore: pageBreak,
    spacing: { line: LINE, after: 240 },
    children: [run(text, { bold: true })],
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    alignment: AlignmentType.LEFT,
    indent: { firstLine: INDENT },
    keepNext: true,
    spacing: { line: LINE, before: 240, after: 120 },
    children: [run(text, { bold: true })],
  });
}

const bullet = (text) =>
  new Paragraph({
    numbering: { reference: "dash", level: 0 },
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: LINE },
    children: Array.isArray(text) ? text : [run(text)],
  });

const numbered = (ref) => (text) =>
  new Paragraph({
    numbering: { reference: ref, level: 0 },
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: LINE },
    children: [run(text)],
  });

