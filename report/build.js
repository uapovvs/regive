const border = { style: BorderStyle.SINGLE, size: 4, color: "000000" };
const borders = { top: border, bottom: border, left: border, right: border };

function table(caption, headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (text, isHeader, w) =>
    new TableCell({
      borders,
      width: { size: w, type: WidthType.DXA },
      verticalAlign: VerticalAlign.CENTER,
      shading: isHeader ? { fill: "E7E6E6", type: ShadingType.CLEAR, color: "auto" } : undefined,
      margins: { top: 40, bottom: 40, left: 80, right: 80 },
      children: [
        new Paragraph({
          alignment: isHeader ? AlignmentType.CENTER : AlignmentType.LEFT,
          children: [new TextRun({ text, font: FONT, size: 24, bold: isHeader })],
        }),
      ],
    });
  return [
    new Paragraph({
      keepNext: true,
      spacing: { line: LINE, before: 120 },
      children: [run(caption)],
    }),
    new Table({
      width: { size: total, type: WidthType.DXA },
      columnWidths: widths,
      rows: [
        new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, true, widths[i])) }),
        ...rows.map((r) => new TableRow({ children: r.map((c, i) => cell(c, false, widths[i])) })),
      ],
    }),
    empty(),
  ];
}

// ---------- Рисунки ----------
let figureNo = 0;
function pngSize(file) {
  const b = fs.readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}

function figure(file, caption) {
  figureNo += 1;
  const full = path.join(SHOTS, file);
  const label = `Рисунок ${figureNo} – ${caption}`;
  if (!fs.existsSync(full)) {
    return [center(`[Скриншот: ${caption}]`, { italics: true }), center(label)];
  }
  const { w, h } = pngSize(full);
  const width = 210;
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      keepNext: true,
      spacing: { before: 120 },
      children: [
        new ImageRun({
          type: "png",
          data: fs.readFileSync(full),
          transformation: { width, height: Math.round((width * h) / w) },
          altText: { title: caption, description: caption, name: file },
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { line: LINE, after: 120 },
      children: [run(label)],
    }),
  ];
}

function code(lines) {
  return lines.map(
    (l) =>
      new Paragraph({
        spacing: { line: 240 },
        children: [new TextRun({ text: l.length ? l : " ", font: "Courier New", size: 20 })],
      }),
  );
}

